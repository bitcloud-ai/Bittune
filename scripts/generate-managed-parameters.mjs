// Core adapter descriptors are the sole source for the Agent-facing surface.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, delimiter } from "node:path";

const root = resolve(import.meta.dirname, "..");
const python = process.env.BITTUNE_CORE_PYTHON || process.env.BITTUNE_TEST_PYTHON || "python3";
const result = spawnSync(python, ["-c", "import json; from bittune_core.adapters import vllm, sglang; from bittune_core.reports import REPORT_REFERENCE_KEYS; from importlib import resources; print(json.dumps({'parameters': {'vllm': vllm.PARAMETERS, 'sglang': sglang.PARAMETERS}, 'report_reference_keys': REPORT_REFERENCE_KEYS, 'acceptance_schema': json.loads((resources.files('bittune_core')/'data/schemas/acceptance-profile.schema.json').read_text())}))"], {
	cwd: root, encoding: "utf8",
	env: { ...process.env, PYTHONPATH: [resolve(root, "packages/bittune-core/src"), process.env.PYTHONPATH].filter(Boolean).join(delimiter) },
});
if (result.status !== 0) throw new Error(result.stderr || String(result.error));
const target = resolve(root, "packages/bittune-runtime/src/harness/managed-parameters.ts");
const exported = JSON.parse(result.stdout);
delete exported.acceptance_schema.$schema;
delete exported.acceptance_schema.$id;
const generated = "// Generated by scripts/generate-managed-parameters.mjs from Core contracts.\nexport const MANAGED_PARAMETERS = " + JSON.stringify(exported.parameters, null, 2) + ";\nexport const MANAGED_REPORT_REFERENCE_KEYS = " + JSON.stringify(exported.report_reference_keys, null, 2) + ";\nexport const MANAGED_ACCEPTANCE_SCHEMA = " + JSON.stringify(exported.acceptance_schema, null, 2) + ";\n";
if (process.argv.includes("--check")) {
	if (readFileSync(target, "utf8") !== generated) throw new Error("Managed parameter drift: regenerate from the Core adapters");
	console.log("Managed parameter descriptors match Core");
} else {
	writeFileSync(target, generated);
}
